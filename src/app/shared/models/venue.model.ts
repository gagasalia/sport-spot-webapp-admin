/**
 * The directory's named towns (the facility form's CITY_OPTIONS covers only
 * the bookable ones). The latin `id` is the stored `city`; any other town is
 * stored as typed. `name` is a live getter — it follows the language toggle.
 */
export const VENUE_CITY_OPTIONS: readonly { id: string; name: string }[] =
  VENUE_CITY_OPTIONS_KA.map(({ id, name }) => ({
    id,
    get name(): string {
      return tr(name);
    },
  }));

/** Display label of a stored city: a named town translates, any other shows as typed. */
export function venueCityName(city: string | undefined | null): string {
  if (!city) return '';
  return VENUE_CITY_OPTIONS.find((c) => c.id === city)?.name ?? city;
}

/** `slug` wire format: lowercase latin words joined by single hyphens. */
export const VENUE_SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** 'HH:mm', 00:00–23:59. */
export const VENUE_TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;

