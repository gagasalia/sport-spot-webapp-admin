/**
 * Articles (blog) — docs/26 §WP-3 moved from markdown-in-repo into an admin
 * module: superadmins write, schedule and publish the player app's `/blog`
 * posts. The body is sanitized rich-text HTML (KA required, EN optional);
 * every EN field falls back to its KA twin on the player app.
 *
 * The lifecycle is a small state machine the API enforces (an invalid
 * transition is a 400); {@link ARTICLE_TRANSITIONS} mirrors it so the UI only
 * ever offers the moves that will succeed.
 */

import { isEnglish, liveLabels } from '../i18n/lang';

export type ArticleStatus = 'draft' | 'ready' | 'scheduled' | 'published' | 'archived';
export type ArticleCategory = 'tips' | 'places' | 'news';

/** The one cover image (media pipeline, docs/22) — web + thumb renditions. */
export interface ArticleCover {
  url: string;
  thumbUrl?: string;
  key?: string;
  thumbKey?: string;
  type: string;
}

/** One FAQ entry — rendered as the post's `FAQPage` JSON-LD block. */
export interface ArticleFaqItem {
  q: string;
  a: string;
  qEn?: string;
  aEn?: string;
}

/** An article as returned by `GET /articles` and `GET /articles/:id`. */
export interface Article {
  _id: string;
  title: string;
  titleEn?: string;
  /** Latin URL slug (`/blog/:slug`); generated by the API when omitted. */
  slug: string;
  excerpt?: string;
  excerptEn?: string;
  bodyHtml: string;
  bodyHtmlEn?: string;
  cover?: ArticleCover | null;
  category: ArticleCategory;
  tags: string[];
  faq: ArticleFaqItem[];
  status: ArticleStatus;
  /** ISO instant a `scheduled` article goes live. */
  publishAt?: string | null;
  /** ISO instant the article (last) went live. */
  publishedAt?: string | null;
  seoTitle?: string;
  seoTitleEn?: string;
  seoDescription?: string;
  seoDescriptionEn?: string;
  /** Facility ids the post links to (CTA cards, internal links). */
  relatedFacilities: string[];
  /** Read-only, computed by the API from the KA body. */
  wordCount: number;
  /** Read-only, computed by the API from the KA body. */
  readingMinutes: number;
  /** Read-only byline («Sport Space რედაქცია»). */
  author: string;
  createdAt?: string;
  updatedAt?: string;
}

/**
 * `POST /articles` body. Optional keys are omitted when empty; the status is
 * not part of it — a new article is always a draft and moves through
 * `PATCH /articles/:id/status`.
 */
export interface CreateArticleDto {
  title: string;
  titleEn?: string;
  slug?: string;
  excerpt?: string;
  excerptEn?: string;
  bodyHtml: string;
  bodyHtmlEn?: string;
  cover?: ArticleCover;
  category: ArticleCategory;
  tags: string[];
  faq: ArticleFaqItem[];
  seoTitle?: string;
  seoTitleEn?: string;
  seoDescription?: string;
  seoDescriptionEn?: string;
  relatedFacilities: string[];
}

/**
 * `PUT /articles/:id` body — every key optional. An explicit `null` clears an
 * optional field server-side (`cover: null` removes the cover image);
 * omitting a key leaves it untouched.
 */
export type UpdateArticleDto = {
  [K in keyof CreateArticleDto]?: CreateArticleDto[K] | null;
};

/** `PATCH /articles/:id/status` body; `publishAt` only with `scheduled`. */
export interface ArticleStatusChange {
  status: ArticleStatus;
  publishAt?: string;
}

/** Query of `GET /articles`; undefined keys are left out of the URL. */
export interface ArticleListQuery {
  page: number;
  limit: number;
  q?: string;
  status?: ArticleStatus;
  category?: ArticleCategory;
}

// ── status machine ──────────────────────────────────────────────────────────

/**
 * Allowed moves, mirrored from the API: draft → ready; draft|ready →
 * published (now) or scheduled (with publishAt); scheduled → ready | draft |
 * published; published → archived; archived → ready | draft.
 */
export const ARTICLE_TRANSITIONS: Readonly<Record<ArticleStatus, readonly ArticleStatus[]>> = {
  draft: ['ready', 'published', 'scheduled'],
  ready: ['published', 'scheduled'],
  scheduled: ['ready', 'draft', 'published'],
  published: ['archived'],
  archived: ['ready', 'draft'],
};

export function canTransition(from: ArticleStatus, to: ArticleStatus): boolean {
  return ARTICLE_TRANSITIONS[from]?.includes(to) ?? false;
}

