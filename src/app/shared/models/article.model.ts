/**
 * Sense override: the dictionary maps «ადგილები» to "Spots" (tournament
 * capacity), but the blog category means places — so the category names
 * carry their own English and read the language signal at render time.
 */
const ARTICLE_CATEGORY_NAMES: Record<ArticleCategory, { ka: string; en: string }> = {
  tips: { ka: 'რჩევები', en: 'Tips' },
  places: { ka: 'ადგილები', en: 'Places' },
  news: { ka: 'სიახლეები', en: 'News' },
};

/** «რჩევები» / "Tips" … — live: call it at render time, never store the result. */
export function articleCategoryLabel(category: ArticleCategory): string {
  const name = ARTICLE_CATEGORY_NAMES[category];
  if (!name) return category;
  return isEnglish() ? name.en : name.ka;
}

export const ARTICLE_STATUSES = Object.keys(ARTICLE_STATUS_LABELS) as ArticleStatus[];
export const ARTICLE_CATEGORIES = Object.keys(ARTICLE_CATEGORY_NAMES) as ArticleCategory[];

// ── caps (mirrored from the API contract, so the form stops before a 400) ───

export const ARTICLE_TITLE_MAX = 160;
export const ARTICLE_EXCERPT_MAX = 300;
export const ARTICLE_SEO_TITLE_MAX = 70;
export const ARTICLE_SEO_DESCRIPTION_MAX = 170;
export const ARTICLE_TAGS_MAX = 10;
export const ARTICLE_FAQ_MAX = 10;
export const ARTICLE_RELATED_FACILITIES_MAX = 6;
/** UI guards (not in the contract): a tag is a short label, a slug a short URL. */
export const ARTICLE_TAG_MAX_LENGTH = 50;
export const ARTICLE_SLUG_MAX = 100;

/** `slug` wire format: lowercase latin words joined by single hyphens. */
export const ARTICLE_SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** docs/26 article spec: 900–1,600 words — below 900 a post reads as thin. */
export const ARTICLE_SEO_MIN_WORDS = 900;
/** Reading speed behind the live «N წთ» estimate (the API's value wins on save). */
export const ARTICLE_WORDS_PER_MINUTE = 200;

/** Minutes to read `words` words; 0 for an empty body. */
export function readingMinutesFor(words: number): number {
  return words > 0 ? Math.max(1, Math.ceil(words / ARTICLE_WORDS_PER_MINUTE)) : 0;
}
